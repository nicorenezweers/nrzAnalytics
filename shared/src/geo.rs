/// Deutscher Name eines Laendercodes (`CH` → `Schweiz`).
pub fn country_name(code: &str) -> Option<&'static str> {
    let code = code.trim();
    if code.len() != 2 {
        return None;
    }
    let upper = code.to_ascii_uppercase();
    COUNTRIES
        .binary_search_by(|(c, _)| (*c).cmp(upper.as_str()))
        .ok()
        .and_then(|i| COUNTRIES.get(i))
        .map(|(_, n)| *n)
}

/// Flaggen-Emoji aus dem Laendercode (`CH` → 🇨🇭); leer bei ungueltigem Code.
pub fn flag(code: &str) -> String {
    let code = code.trim();
    if code.len() != 2 || !code.bytes().all(|b| b.is_ascii_alphabetic()) {
        return String::new();
    }
    code.to_ascii_uppercase()
        .bytes()
        .filter_map(|b| char::from_u32(0x1F1E6 + u32::from(b - b'A')))
        .collect()
}

/// Laendercode aus einem Namen oder Code (fuer Filter-Eingaben).
pub fn country_code(input: &str) -> Option<&'static str> {
    let t = input.trim();
    COUNTRIES
        .iter()
        .find(|(c, n)| c.eq_ignore_ascii_case(t) || n.to_lowercase() == t.to_lowercase())
        .map(|(c, _)| *c)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sorted_and_lookup() {
        assert!(
            COUNTRIES.windows(2).all(|w| w[0].0 < w[1].0),
            "COUNTRIES muss sortiert sein"
        );
        assert_eq!(country_name("ch"), Some("Schweiz"));
        assert_eq!(country_name("XX"), None);
        assert_eq!(flag("CH"), "🇨🇭");
        assert_eq!(country_code("Deutschland"), Some("DE"));
    }
}
